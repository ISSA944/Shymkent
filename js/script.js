function initAdvantagesTabs() {
  const tabs = Array.from(document.querySelectorAll(".advantages-tab"));
  const cards = Array.from(document.querySelectorAll(".advantage-card[data-adv]"));
  if (!tabs.length || !cards.length) return;

  const mq = window.matchMedia("(max-width: 1300px)");

  const setActive = (key) => {
    tabs.forEach((tab) => {
      const isActive = tab.getAttribute("data-adv-target") === key;
      tab.classList.toggle("is-active", isActive);
      tab.setAttribute("aria-selected", isActive ? "true" : "false");
    });
    cards.forEach((card) => {
      const isActive = card.getAttribute("data-adv") === key;
      card.classList.toggle("is-active", isActive);
      card.hidden = !isActive;
    });
  };

  const applyMode = () => {
    if (!mq.matches) {
      cards.forEach((card) => {
        card.hidden = false;
        card.classList.remove("is-active");
      });
      return;
    }
    const activeTab = tabs.find((t) => t.classList.contains("is-active")) || tabs[0];
    const key = activeTab.getAttribute("data-adv-target");
    if (key) setActive(key);
  };

  tabs.forEach((tab) => {
    tab.addEventListener("click", () => {
      const key = tab.getAttribute("data-adv-target");
      if (key) setActive(key);
    });
  });

  applyMode();
  if (mq.addEventListener) {
    mq.addEventListener("change", applyMode);
  } else {
    mq.addListener(applyMode);
  }
}

