function initProductsMarquee() {
  const track = document.querySelector('.products-track');
  if (!track) return;

  // duplicate children once to create seamless loop
  if (track.dataset.marquee !== '1') {
    track.dataset.originalCount = String(track.children.length);
    const originalHTML = track.innerHTML;
    track.innerHTML = originalHTML + originalHTML;
    track.dataset.marquee = '1';
  }

  // Use exact half of duplicated track width for truly seamless loop.
  const speed = 320; // px/s
  const distance = track.scrollWidth / 2;
  if (!Number.isFinite(distance) || distance <= 0) return;
  const duration = Math.max(8, distance / speed);

  track.style.setProperty('--marquee-distance', distance + 'px');
  track.style.animationDuration = duration.toFixed(2) + 's';
  track.style.animationTimingFunction = 'linear';
  track.style.animationIterationCount = 'infinite';
}

window.addEventListener('load', initProductsMarquee);
window.addEventListener('resize', () => {
  // recalc on resize (small debounce)
  clearTimeout(window._productsMarqueeTimer);
  window._productsMarqueeTimer = setTimeout(initProductsMarquee, 250);
});

function initPartnersForm() {
  const form = document.getElementById("partnersForm");
  if (!form) return;

  const nameInput = form.querySelector('input[name="name"]');
  const phoneInput = form.querySelector('input[name="phone"]');
  if (!nameInput || !phoneInput) return;
  const nameField = nameInput.closest(".partners__field");
  const phoneField = phoneInput.closest(".partners__field");

  const createError = (input) => {
    const el = document.createElement("div");
    el.className = "partners__error";
    input.insertAdjacentElement("afterend", el);
    return el;
  };

  const nameError = createError(nameInput);
  const phoneError = createError(phoneInput);
  const successEl = document.createElement("div");
  successEl.className = "partners__success";
  form.insertAdjacentElement("beforeend", successEl);
  const submitBtn = form.querySelector('button[type="submit"]');

  const t = (key) => {
    return tGlobal(key);
  };

  function validateName(value) {
    const v = (value || "").trim();
    if (!v) return t("form_error_name_required");

    const words = v.split(/\s+/).filter(Boolean);
    if (!words.length || words.some((w) => w.length < 2)) {
      return t("form_error_name_short");
    }

    if (!/[A-Za-zА-Яа-яЁё]/.test(v)) {
      return t("form_error_name_invalid");
    }

    return "";
  }

  function validatePhone(value) {
    const v = (value || "").trim();
    if (!v) return t("form_error_phone_required");
    if (/[A-Za-zА-Яа-яЁё]/.test(v)) return t("form_error_phone_invalid");
    if (!/^[\d\s()+-]+$/.test(v)) return t("form_error_phone_invalid");
    const clean = v.replace(/\D+/g, "");
    if (!/^7\d{10}$/.test(clean)) return t("form_error_phone_invalid");
    return "";
  }

  function renderErrors() {
    const nameMsg = validateName(nameInput.value);
    const phoneMsg = validatePhone(phoneInput.value);
    nameError.textContent = nameMsg;
    phoneError.textContent = phoneMsg;
    return !nameMsg && !phoneMsg;
  }

  nameInput.addEventListener("input", () => {
    if (nameField) nameField.classList.toggle("is-active", Boolean(nameInput.value.trim()));
    if (nameError.textContent) {
      nameError.textContent = validateName(nameInput.value);
    }
  });

  phoneInput.addEventListener("input", () => {
    if (phoneField) phoneField.classList.toggle("is-active", Boolean(phoneInput.value.trim()));
    if (phoneError.textContent) {
      phoneError.textContent = validatePhone(phoneInput.value);
    }
  });

  nameInput.addEventListener("focus", () => {
    if (nameField) nameField.classList.add("is-active");
  });
  nameInput.addEventListener("blur", () => {
    if (nameField) nameField.classList.toggle("is-active", Boolean(nameInput.value.trim()));
  });

  phoneInput.addEventListener("focus", () => {
    if (phoneField) phoneField.classList.add("is-active");
  });
  phoneInput.addEventListener("blur", () => {
    if (phoneField) phoneField.classList.toggle("is-active", Boolean(phoneInput.value.trim()));
  });

  form.addEventListener("submit", async (e) => {
    e.preventDefault();
    successEl.textContent = "";
    successEl.dataset.state = "";
    successEl.dataset.errorKey = "";
    successEl.style.color = "#02964C";
    if (!renderErrors()) {
      return;
    }

    if (submitBtn) {
      submitBtn.disabled = true;
      submitBtn.textContent = t("form_sending");
    }

    const response = await submitToWeb3Forms(
      {
        name: nameInput.value.trim(),
        phone: phoneInput.value.trim(),
        form_type: "partners",
        language: getCurrentLang(),
        page_url: window.location.href
      },
      "Partners form submission"
    );

    if (!response.ok) {
      successEl.style.color = "#B42318";
      successEl.dataset.state = "error";
      successEl.dataset.errorKey = response.errorKey || "form_send_error";
      successEl.textContent = t(successEl.dataset.errorKey);
    } else {
      form.reset();
      nameError.textContent = "";
      phoneError.textContent = "";
      if (nameField) nameField.classList.remove("is-active");
      if (phoneField) phoneField.classList.remove("is-active");
      successEl.style.color = "#02964C";
      successEl.dataset.state = "success";
      successEl.dataset.errorKey = "";
      successEl.textContent = t("form_success");
    }

    if (submitBtn) {
      submitBtn.disabled = false;
      submitBtn.textContent = t("form_button");
    }
  });

  const langObserver = new MutationObserver(() => {
    if (nameError.textContent) nameError.textContent = validateName(nameInput.value);
    if (phoneError.textContent) phoneError.textContent = validatePhone(phoneInput.value);
    if (successEl.dataset.state === "success") {
      successEl.textContent = t("form_success");
    } else if (successEl.dataset.state === "error") {
      successEl.textContent = t(successEl.dataset.errorKey || "form_send_error");
    }
  });

  langObserver.observe(document.documentElement, { attributes: true, attributeFilter: ["lang"] });
}

