const WEB3FORMS_ENDPOINT = "https://api.web3forms.com/submit";
const WEB3FORMS_ACCESS_KEY = (
  (window.WEB3FORMS_ACCESS_KEY || "") ||
  (document.body && document.body.dataset ? document.body.dataset.web3AccessKey : "") ||
  ""
).trim();

function getCurrentLang() {
  const lang = (document.documentElement.lang || "ru").toLowerCase();
  return lang.startsWith("en") ? "en" : "ru";
}

function tGlobal(key) {
  const lang = getCurrentLang();
  return (translations[lang] && translations[lang][key]) || "";
}

async function submitToWeb3Forms(fields, subject) {
  if (!WEB3FORMS_ACCESS_KEY) {
    return { ok: false, errorKey: "form_send_missing_key" };
  }

  const payload = {
    access_key: WEB3FORMS_ACCESS_KEY,
    subject: subject || "Website form submission",
    from_name: "Shymkentmai landing",
    ...fields
  };

  try {
    const response = await fetch(WEB3FORMS_ENDPOINT, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json"
      },
      body: JSON.stringify(payload)
    });

    const result = await response.json().catch(() => ({}));
    if (response.ok && result && result.success) {
      return { ok: true };
    }

    return { ok: false, errorKey: "form_send_error" };
  } catch (error) {
    return { ok: false, errorKey: "form_send_error" };
  }
}

function setPreloaderVisible(visible) {
  const preloader = document.querySelector("[data-preloader]");
  if (!preloader) return;

  preloader.classList.toggle("is-hidden", !visible);
  preloader.setAttribute("aria-hidden", visible ? "false" : "true");
  document.body.classList.toggle("is-loading", visible);
}

function switchLanguageWithPreloader(nextLang, options = {}) {
  const keepMenuOpen = options.keepMenuOpen !== false;
  const now = Date.now();
  if (preloaderState.isSwitchingLanguage || now - preloaderState.lastToggleAt < 500) return;
  preloaderState.lastToggleAt = now;
  preloaderState.isSwitchingLanguage = true;

  const wasMenuOpen = !!(mobileMenu && mobileMenu.classList.contains("open"));
  if (wasMenuOpen && !keepMenuOpen) {
    mobileMenu.classList.remove("open");
    if (burgerBtn) {
      burgerBtn.classList.remove("active");
      burgerBtn.setAttribute("aria-expanded", "false");
    }
    document.body.classList.remove("menu-open");
    document.body.style.overflow = "";
  }
  const lastScrollY = window.scrollY;
  setPreloaderVisible(true);
  applyLanguage(nextLang);
  startPreloaderTextCycle();
  window.scrollTo(0, lastScrollY);

  setTimeout(() => {
    setPreloaderVisible(false);
    preloaderState.isSwitchingLanguage = false;
    stopPreloaderTextCycle();
    window.scrollTo(0, lastScrollY);
    if (wasMenuOpen && mobileMenu && keepMenuOpen) {
      mobileMenu.classList.add("open");
      burgerBtn.classList.add("active");
      burgerBtn.setAttribute("aria-expanded", "true");
      document.body.classList.add("menu-open");
      document.body.style.overflow = "hidden";
    }
  }, 800);
}

function startPreloaderTextCycle() {
  const preloader = document.querySelector("[data-preloader]");
  const subtitle = preloader ? preloader.querySelector(".site-preloader__subtitle") : null;
  if (!subtitle) return;

  stopPreloaderTextCycle();

  const lang = (document.documentElement.lang || "ru").toLowerCase().startsWith("en") ? "en" : "ru";
  const list = preloaderState.messages[lang] || preloaderState.messages.ru;
  subtitle.textContent = list[0];
}

function stopPreloaderTextCycle() {
  if (preloaderState.ticker) {
    clearInterval(preloaderState.ticker);
    preloaderState.ticker = null;
  }
}

function initPreloader() {
  const preloader = document.querySelector("[data-preloader]");
  if (!preloader) {
    document.body.classList.remove("is-loading");
    return;
  }

  const startedAt = performance.now();
  const minVisibleMs = 2600;
  let isHidden = false;
  startPreloaderTextCycle();

  const hidePreloader = () => {
    if (isHidden) return;
    isHidden = true;
    const elapsed = performance.now() - startedAt;
    const delay = Math.max(0, minVisibleMs - elapsed);

    setTimeout(() => {
      setPreloaderVisible(false);
      stopPreloaderTextCycle();
    }, delay);
  };

  window.addEventListener("load", hidePreloader, { once: true });
  setTimeout(hidePreloader, 5200);
}

initPreloader();

// Apply language to elements with data-i18n and data-i18n-placeholder
function applyLanguage(lang) {
  const dict = translations[lang] || translations.ru;
  document.documentElement.lang = lang;
  if (dict.site_title) document.title = dict.site_title;

  // text nodes
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  // placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key) return;
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  // save
  try { localStorage.setItem(LS_KEY, lang); } catch (e) {}

  // update buttons (any element with data-lang)
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    const btnLang = btn.getAttribute("data-lang");
    const isActive = btnLang === lang;
    btn.classList.toggle("is-active", isActive);
    if (btn.getAttribute("role") === "button" || btn.tagName === "BUTTON") {
      btn.setAttribute("aria-pressed", isActive ? "true" : "false");
    }
  });

  // single toggle button (RU/EN)
  document.querySelectorAll("#langToggle, [data-lang-toggle]").forEach((toggle) => {
    toggle.textContent = lang.toUpperCase();
    toggle.setAttribute("aria-pressed", "true");
  });

  // re-create icons if needed
  if (window.lucide && typeof window.lucide.createIcons === "function") {
    window.lucide.createIcons();
  }
}

// Initialize language switcher
function initLangSwitcher() {
  document.addEventListener("click", (e) => {
    const btn = e.target.closest("[data-lang]");
    if (btn) {
      const lang = btn.getAttribute("data-lang");
      if (!lang) return;
      switchLanguageWithPreloader(lang);
      return;
    }

    const toggle = e.target.closest("#langToggle, [data-lang-toggle]");
    if (toggle) {
      const current = localStorage.getItem(LS_KEY) || "ru";
      const next = current === "ru" ? "en" : "ru";
      switchLanguageWithPreloader(next);
    }
  });

  // apply on load
  document.addEventListener("DOMContentLoaded", () => {
    const saved = localStorage.getItem(LS_KEY) || (navigator.language && navigator.language.startsWith("en") ? "en" : "ru");
    applyLanguage(saved);
  });
}

// Run init
initLangSwitcher();

