function initGallerySlider() {
  const slider = document.getElementById("gallerySlider");
  const track = document.getElementById("galleryTrack");
  if (!slider || !track) return;

  const viewport = slider.querySelector(".gallery-slider__viewport");
  const prevBtn = slider.querySelector(".gallery-arrow.prev");
  const nextBtn = slider.querySelector(".gallery-arrow.next");
  const counter = document.getElementById("galleryCounter");
  const counterCurrent = counter ? counter.querySelector(".gallery-counter__current") : null;
  const counterTotal = counter ? counter.querySelector(".gallery-counter__total") : null;

  const slides = [
    { src: "assets/image (3).png", alt: "Production facilities" },
    { src: "assets/image (4).png", alt: "Product packaging" },
    { src: "assets/image (5).png", alt: "Production equipment" }
  ];

  if (slides.length === 0) return;

  const renderSlides = [slides[slides.length - 1], ...slides, slides[0]];
  track.innerHTML = renderSlides.map((slide, i) => {
    const activeClass = i === 1 ? " is-active" : "";
    return `<div class="gallery-slide${activeClass}" data-slide-index="${i}"><img src="${slide.src}" alt="${slide.alt}" loading="lazy"></div>`;
  }).join("");

  let index = 1;
  let isAnimating = false;
  let isDragging = false;
  let dragStartX = 0;
  let dragDelta = 0;

  function formatNum(value) {
    return String(value).padStart(2, "0");
  }

  function getRealIndex() {
    if (index === 0) return slides.length;
    if (index === slides.length + 1) return 1;
    return index;
  }

  function updateCounter() {
    if (counterCurrent) counterCurrent.textContent = formatNum(getRealIndex());
    if (counterTotal) counterTotal.textContent = formatNum(slides.length);
  }

  function getStep() {
    const first = track.querySelector(".gallery-slide");
    if (!first) return 0;
    const gap = parseFloat(getComputedStyle(track).gap || 0);
    return first.getBoundingClientRect().width + gap;
  }

  function getOffsetByIndex(i) {
    const slide = track.children[i];
    if (!slide || !viewport) return 0;
    const step = getStep();
    return -(i * step);
  }

  function markActiveSlide() {
    const all = track.querySelectorAll(".gallery-slide");
    all.forEach((el) => el.classList.remove("is-active"));
    const active = track.children[index];
    if (active) active.classList.add("is-active");
  }

  function applyTransform(animated) {
    track.style.transition = animated
      ? "transform 0.6s cubic-bezier(0.22, 1, 0.36, 1)"
      : "none";
    track.style.transform = `translate3d(${getOffsetByIndex(index)}px, 0, 0)`;
    markActiveSlide();
    updateCounter();
  }

  function goTo(nextIndex) {
    if (isAnimating) return;
    isAnimating = true;
    index = nextIndex;
    applyTransform(true);
  }

  function next() {
    goTo(index + 1);
  }

  function prev() {
    goTo(index - 1);
  }

  track.addEventListener("transitionend", () => {
    if (index === 0) {
      index = slides.length;
      applyTransform(false);
    } else if (index === slides.length + 1) {
      index = 1;
      applyTransform(false);
    }
    isAnimating = false;
  });

  if (nextBtn) nextBtn.addEventListener("click", next);
  if (prevBtn) prevBtn.addEventListener("click", prev);

  document.addEventListener("keydown", (e) => {
    const tag = (e.target && e.target.tagName) ? e.target.tagName.toLowerCase() : "";
    if (tag === "input" || tag === "textarea") return;
    if (e.key === "ArrowRight") next();
    if (e.key === "ArrowLeft") prev();
  });

  if (viewport) {
    viewport.addEventListener("pointerdown", (e) => {
      if (isAnimating) return;
      isDragging = true;
      dragStartX = e.clientX;
      dragDelta = 0;
      viewport.classList.add("is-dragging");
      viewport.setPointerCapture(e.pointerId);
      track.style.transition = "none";
    });

    viewport.addEventListener("pointermove", (e) => {
      if (!isDragging) return;
      dragDelta = e.clientX - dragStartX;
      const base = getOffsetByIndex(index);
      track.style.transform = `translate3d(${base + dragDelta}px, 0, 0)`;
    });

    const finishDrag = () => {
      if (!isDragging) return;
      isDragging = false;
      viewport.classList.remove("is-dragging");
      const threshold = 60;
      if (dragDelta < -threshold) {
        next();
      } else if (dragDelta > threshold) {
        prev();
      } else {
        applyTransform(true);
      }
      dragDelta = 0;
    };

    viewport.addEventListener("pointerup", finishDrag);
    viewport.addEventListener("pointercancel", finishDrag);
    viewport.addEventListener("pointerleave", finishDrag);
  }

  window.addEventListener("resize", () => applyTransform(false));

  requestAnimationFrame(() => {
    applyTransform(false);
  });
}

