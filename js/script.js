function buildMobileMenu() {
  if (!mobileMenu || !nav) return;
  let list = mobileMenu.querySelector("ul");
  if (!list || mobileMenu.dataset.built !== "1") {
    mobileMenu.innerHTML = "";
    list = document.createElement("ul");
    const links = Array.from(nav.querySelectorAll("a"));
    links.forEach((link) => {
      const li = document.createElement("li");
      const clone = link.cloneNode(true);
      li.appendChild(clone);
      list.appendChild(li);
    });

    const lang = document.querySelector(".lang");
    if (lang) {
      const langClone = lang.cloneNode(true);
      const toggleBtn = langClone.querySelector("#langToggle");
      if (toggleBtn) {
        toggleBtn.removeAttribute("id");
        toggleBtn.setAttribute("data-lang-toggle", "1");
      }
      langClone.classList.add("mobile-nav__lang");
      const langLi = document.createElement("li");
      langLi.className = "mobile-nav__lang-row";
      langLi.appendChild(langClone);
      list.appendChild(langLi);
    }

    mobileMenu.appendChild(list);
    mobileMenu.dataset.built = "1";
    updateActiveLink();
  }

  if (!mobileMenu.querySelector(".mobile-nav__lang")) {
    mobileMenu.dataset.built = "0";
    buildMobileMenu();
  }
}

